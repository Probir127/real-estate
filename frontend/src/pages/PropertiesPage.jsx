            lng: p.longitude || 90.4125,
            beds: p.bedrooms || 0,
            baths: p.bathrooms || 0,
            balconies: p.balconies || 2,
            sqft: p.area_sqft || 1200,
            floor: p.floor || 4,
            totalFloors: 10,
