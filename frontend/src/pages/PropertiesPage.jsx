// Formatting helpers
function formatBDT(amount) {
  if (!amount) return '—';
  const n = Number(amount);
  if (n >= 10000000) {
    return `৳ ${(n / 10000000).toFixed(2).replace(/\.?0+$/, '')} Crore`;
  }
  if (n >= 100000) {
    return `৳ ${(n / 100000).toFixed(n % 100000 === 0 ? 0 : 2).replace(/\.?0+$/, '')} Lakh`;
  }
  if (n >= 1000) {
    return `৳ ${Math.round(n / 1000)}K`;
  }
  return `৳ ${n.toLocaleString()}`;
}

